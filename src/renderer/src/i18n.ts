const dictionaries: Record<'ru' | 'en', Record<string, string>> = { ru, en }

function interpolate(s: string, vars?: Vars): string {
  if (!vars) return s
  return s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m))
}

function translate(lang: 'ru' | 'en', key: string, vars?: Vars): string {
  const s = dictionaries[lang][key] ?? key
  return interpolate(s, vars)
}

/** Translate `key` (Russian text or id) into the current language. Unknown keys are returned as is. */
export function t(key: string, vars?: Vars): string {
  return translate(uiStore.getState().lang, key, vars)
}

/** Hook version of `t` that re-renders the component when the language changes. */
export function useT(): typeof t {
  const lang = useUi((s) => s.lang)
  return useCallback((key: string, vars?: Vars) => translate(lang, key, vars), [lang])
}

/** Register extra translations at runtime (e.g. from a module that owns many strings). */
export function addTranslations(lang: 'ru' | 'en', entries: Record<string, string>): void {
  Object.assign(dictionaries[lang], entries)
}
